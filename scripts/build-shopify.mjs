// Copies the web app's build output into the Shopify theme so both storefronts share one design.
// Run after `vite build` (see `npm run build:shopify`).
//   dist/assets/index-*.css   -> verenne-theme/assets/vr-app.css
//   src/data.js               -> verenne-theme/assets/vr-data.js  (window.VR_DATA)
//   lenis                     -> verenne-theme/assets/vr-lenis.js
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assets = path.join(root, 'verenne-theme', 'assets');

// 1. Stylesheet
const distAssets = path.join(root, 'dist', 'assets');
const css = fs.readdirSync(distAssets).find((f) => /^index-.*\.css$/.test(f));
if (!css) throw new Error('No compiled CSS in dist/assets — run `vite build` first.');
fs.copyFileSync(path.join(distAssets, css), path.join(assets, 'vr-app.css'));

// 2. Catalogue data. Paths become bare asset file names; vr-app.js prefixes the theme's asset URL.
const data = await import(pathToFileURL(path.join(root, 'src', 'data.js')).href);
const strip = (p) => (p ? p.replace(/^.*\/products\//, '') : p);
const payload = {
  products: data.PRODUCTS.map((p) => ({ ...p, image: strip(p.image), portrait: strip(p.portrait) })),
  categories: data.CATEGORIES,
  ritual: data.RITUAL
};
fs.writeFileSync(
  path.join(assets, 'vr-data.js'),
  `/* Generated by scripts/build-shopify.mjs from src/data.js — do not edit by hand. */\nwindow.VR_DATA = ${JSON.stringify(payload)};\n`
);

// 3. Smooth scroll library (same version as the web app)
fs.copyFileSync(path.join(root, 'node_modules', 'lenis', 'dist', 'lenis.min.js'), path.join(assets, 'vr-lenis.js'));

console.log(`Shopify assets updated from ${css}`);
